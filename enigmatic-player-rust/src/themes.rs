use ratatui::style::Color;

#[derive(Clone, Copy)]
pub struct Theme {
    pub name: &'static str,
    pub bg: Color,
    pub panel: Color,
    pub sel: Color,
    pub line: Color,
    pub text: Color,
    pub dim: Color,
    pub red: Color,
    pub cyan: Color,
    pub green: Color,
    pub purple: Color,
    pub yellow: Color,
}

const fn c(v: u32) -> Color {
    Color::Rgb((v >> 16) as u8, (v >> 8) as u8, v as u8)
}

const fn th(name: &'static str, v: [u32; 11]) -> Theme {
    Theme {
        name,
        bg: c(v[0]),
        panel: c(v[1]),
        sel: c(v[2]),
        line: c(v[3]),
        text: c(v[4]),
        dim: c(v[5]),
        red: c(v[6]),
        cyan: c(v[7]),
        green: c(v[8]),
        purple: c(v[9]),
        yellow: c(v[10]),
    }
}

